def _field_to_json(spec: FieldSpec) -> JSONObject:
    return {
        "name": spec.name,
        "crop_type": spec.crop_type,
        "area_ha": spec.area_ha,
        "meters_per_pixel": spec.meters_per_pixel,
        "location": spec.location,
        "notes": spec.notes,
        "boundary_points": [[x, y] for (x, y) in spec.boundary_points],
        "images": [
            {
                "image_id": img.image_id,
                "filename": img.filename,
                "source": img.source,
                "url": img.url,
                "width_px": img.width_px,
                "height_px": img.height_px,
                "uploaded_ms": img.uploaded_ms,
            }
            for img in spec.images
        ],
        "zones": [
            {
                "zone_id": z.zone_id,
                "kind": z.kind,
                "label": z.label,
                "crop_type": z.crop_type,
                "enabled": z.enabled,
                "boundary_points": [[x, y] for (x, y) in z.boundary_points],
            }
            for z in spec.zones
        ],
        "obstacles": [
            {
                "obstacle_id": o.obstacle_id,
                "kind": o.kind,
                "label": o.label,
                "points": [[x, y] for (x, y) in o.points],
            }
            for o in spec.obstacles
        ],
    }


def _field_from_json(data: JSONObject) -> FieldSpec:
    return FieldSpec(
        name=_require_str(data.get("name"), "field.name"),
        crop_type=_as_str(data.get("crop_type"), "generic"),
        area_ha=_as_opt_float(data.get("area_ha")),
        meters_per_pixel=_as_float(data.get("meters_per_pixel"), 0.5),
        location=_as_str(data.get("location"), ""),
        notes=_as_str(data.get("notes"), ""),
        boundary_points=_points_from_json(data.get("boundary_points")),
        images=[_image_from_json(i) for i in _as_list(data.get("images"))],
        zones=[_zone_from_json(z) for z in _as_list(data.get("zones"))],
        obstacles=[_obstacle_from_json(o) for o in _as_list(data.get("obstacles"))],
    )


def _image_from_json(data: JSONObject) -> FieldImage:
    return FieldImage(
        image_id=_as_str(data.get("image_id"), f"img_{uuid.uuid4().hex[:8]}"),
        filename=_as_str(data.get("filename"), ""),
        source=_as_str(data.get("source"), "manual"),
        url=_as_str(data.get("url"), ""),
        width_px=_as_int(data.get("width_px"), 0),
        height_px=_as_int(data.get("height_px"), 0),
        uploaded_ms=_as_int(data.get("uploaded_ms"), 0),
    )


def _zone_from_json(data: JSONObject) -> Zone:
    return Zone(
        zone_id=_as_str(data.get("zone_id"), f"zone_{uuid.uuid4().hex[:8]}"),
        kind=_as_str(data.get("kind"), "crop"),
        label=_as_str(data.get("label"), ""),
        crop_type=_as_opt_str(data.get("crop_type")),
        enabled=bool(data.get("enabled", True)),
        boundary_points=_points_from_json(data.get("boundary_points")),
    )


def _obstacle_from_json(data: JSONObject) -> Obstacle:
    return Obstacle(
        obstacle_id=_as_str(data.get("obstacle_id"), f"obs_{uuid.uuid4().hex[:8]}"),
        kind=_as_str(data.get("kind"), "restricted"),
        label=_as_str(data.get("label"), ""),
        points=_points_from_json(data.get("points")),
    )


def _fleet_item_from_json(data: JSONObject) -> FleetItem:
    return FleetItem(
        drone_id=_as_int(data.get("drone_id"), 0),
        model=_as_str(data.get("model"), "ORION-Std"),
        vendor=_as_str(data.get("vendor"), "ORION"),
        battery_capacity_mah=_as_float(data.get("battery_capacity_mah"), 16000.0),
        liquid_capacity_l=_as_float(data.get("liquid_capacity_l"), 10.0),
        working_width_m=_as_opt_float(data.get("working_width_m")),
    )


def _product_from_json(data: JSONObject) -> ProductSelection:
    return ProductSelection(
        product_id=_as_str(data.get("product_id"), f"prod_{uuid.uuid4().hex[:8]}"),
        name=_as_str(data.get("name"), ""),
        rate_l_per_ha=_as_opt_float(data.get("rate_l_per_ha")),
        tank=_as_opt_str(data.get("tank")),
        concentration_pct=_as_opt_float(data.get("concentration_pct")),
        dilution=_as_opt_str(data.get("dilution")),
        safety_notes=_as_str(data.get("safety_notes"), ""),
    )


# ---------------------------------------------------------------------------
# Typed coercion helpers (avoid Any / getattr)
# ---------------------------------------------------------------------------


class DefinitionValidationError(ValueError):
    """Raised when an incoming Mission Definition payload is malformed."""


def _as_object(value: JSONValue) -> JSONObject:
    return value if isinstance(value, dict) else {}


def _require_object(value: JSONValue, name: str) -> JSONObject:
    if not isinstance(value, dict):
        raise DefinitionValidationError(f"'{name}' must be an object")
    return value


def _as_list(value: JSONValue) -> list[JSONObject]:
    if not isinstance(value, list):
        return []
    return [item for item in value if isinstance(item, dict)]


def _points_from_json(value: JSONValue) -> list[tuple[float, float]]:
    if not isinstance(value, list):
        return []
    points: list[tuple[float, float]] = []
    for item in value:
        if isinstance(item, list) and len(item) >= 2:
            x, y = item[0], item[1]
            if isinstance(x, (int, float)) and isinstance(y, (int, float)):
                points.append((float(x), float(y)))
    return points


def _require_str(value: JSONValue, name: str) -> str:
    if not isinstance(value, str) or not value.strip():
        raise DefinitionValidationError(f"'{name}' is required and must be a string")
    return value


def _as_str(value: JSONValue, default: str) -> str:
    return value if isinstance(value, str) else default


def _as_opt_str(value: JSONValue) -> Optional[str]:
    return value if isinstance(value, str) else None


def _as_int(value: JSONValue, default: int) -> int:
    if isinstance(value, bool):
        return default
    if isinstance(value, int):
        return value
    if isinstance(value, float):
        return int(value)
    return default


def _as_float(value: JSONValue, default: float) -> float:
    if isinstance(value, bool):
        return default
    if isinstance(value, (int, float)):
        return float(value)
    return default


def _as_opt_float(value: JSONValue) -> Optional[float]:
    if isinstance(value, bool):
        return None
    if isinstance(value, (int, float)):
        return float(value)
    return None

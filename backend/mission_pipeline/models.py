"""
Mission Definition Pipeline — data models (the central contract).

These are plain, serializable dataclasses. They carry operator-authored,
design-time intent only. No planning, optimization, or decision logic lives
here — that remains in core/ (the Planning Core).

Two artifacts:
    MissionDefinition : editable, persisted, owned by Mission Planning.
    MissionPackage    : generated by the Planning Core from a definition;
                        execution-ready input for the Digital Twin.

Sub-phases 10D.3-10D.7 enrich MissionDefinition (zones, obstacles, products,
scheduling metadata, ...) without changing this contract's shape.
"""

from __future__ import annotations

import time
import uuid
from dataclasses import dataclass, field
from typing import Optional

from backend.serializers import JSONObject, JSONValue

# ---------------------------------------------------------------------------
# Mission Definition (design-time input)
# ---------------------------------------------------------------------------


@dataclass
class Zone:
    """An operator-drawn area (crop/management/exclusion). Enriched in 10D.3-4."""

    zone_id: str
    kind: str  # "crop" | "management" | "exclusion" | "treatment"
    label: str
    boundary_points: list[tuple[float, float]]  # local metric (x, y) meters
    crop_type: Optional[str] = None
    enabled: bool = True


@dataclass
class Obstacle:
    """An operator-drawn obstacle/infrastructure marker. Enriched in 10D.3."""

    obstacle_id: str
    kind: str  # "tree" | "pole" | "building" | "irrigation" | "road" | "restricted"
    label: str
    points: list[tuple[float, float]]  # local metric (x, y) meters


@dataclass
class FieldImage:
    """A reference to an uploaded field image (satellite/drone/manual)."""

    image_id: str
    filename: str
    source: str  # "satellite" | "drone" | "manual"
    url: str
    width_px: int = 0
    height_px: int = 0
    uploaded_ms: int = 0


@dataclass
class FieldSpec:
    """
    Field information + preparation data (Phase 10D.3).

    boundary_points, zones and obstacles are user-drawn local metric vertices
    (meters); when boundary is absent, the Planning Core falls back to a
    synthetic rectangle from area_ha (v0.1 compat).

    meters_per_pixel relates the annotation image to metric space so operator
    drawings on the uploaded image become metric geometry the Planning Core
    consumes. Annotation happens in the UI only — no planning is performed here.
    """

    name: str
    crop_type: str
    boundary_points: list[tuple[float, float]] = field(default_factory=list)
    area_ha: Optional[float] = None
    zones: list[Zone] = field(default_factory=list)
    obstacles: list[Obstacle] = field(default_factory=list)
    images: list[FieldImage] = field(default_factory=list)
    meters_per_pixel: float = 0.5
    location: str = ""
    notes: str = ""


@dataclass
class EnvironmentParams:
    """Environmental information consumed by the Planning Core."""

    temperature_c: float = 25.0
    wind_speed_kmh: float = 10.0


@dataclass
class OperationParams:
    """
    Operator planning preferences (intent only — never a computed plan).

    The Mission Designer (10D.4) captures additional preferences (speed,
    overlap, safety margin, coverage direction, route preference). These are
    hints only: the Planning Core decides how to use them. They are optional so
    earlier (10D.2/10D.3) payloads deserialize unchanged.
    """

    operation_type: str = "spray"
    num_drones: int = 3
    flight_altitude_m: Optional[float] = None
    planning_mode: str = "automatic"  # "manual" | "assisted" | "automatic"
    nominal_speed_ms: Optional[float] = None
    overlap_pct: Optional[float] = None
    safety_margin_m: Optional[float] = None
    coverage_direction: str = "auto"  # "auto" | "north_south" | "east_west"
    route_preference: str = "balanced"  # "balanced" | "time" | "battery"


@dataclass
class ProductSelection:
    """
    A chemical/product association (available assets, not allocation).

    The Mission Designer (10D.4) captures application details (tank,
    concentration, dilution, safety notes). These are optional so earlier
    payloads deserialize unchanged. No consumption/allocation is computed here.
    """

    product_id: str
    name: str
    rate_l_per_ha: Optional[float] = None
    tank: Optional[str] = None
    concentration_pct: Optional[float] = None
    dilution: Optional[str] = None
    safety_notes: str = ""


@dataclass
class FleetItem:
    """A selected available drone/asset (selection, not task assignment)."""

    drone_id: int
    model: str
    vendor: str
    battery_capacity_mah: float
    liquid_capacity_l: float
    working_width_m: Optional[float] = None


@dataclass
class MissionDefinition:
    """The central, editable contract every planning screen writes to."""

    name: str
    field: FieldSpec
    operation: OperationParams = field(default_factory=OperationParams)
    environment: EnvironmentParams = field(default_factory=EnvironmentParams)
    fleet: list[FleetItem] = field(default_factory=list)
    products: list[ProductSelection] = field(default_factory=list)
    description: str = ""
    # Mission information captured by the Mission Designer (10D.4). Design-time
    # metadata only — no scheduling/priority logic is performed on these.
    field_id: str = ""
    priority: str = "normal"  # "low" | "normal" | "high" | "urgent"
    scheduled_date: str = ""  # operator estimate (ISO date), not a schedule
    notes: str = ""
    id: str = field(default_factory=lambda: f"mission_{uuid.uuid4().hex[:12]}")
    version: int = 1
    created_ms: int = field(default_factory=lambda: int(time.time() * 1000))
    updated_ms: int = field(default_factory=lambda: int(time.time() * 1000))

    # -- (de)serialization ---------------------------------------------------

    def to_json(self) -> JSONObject:
        return {
            "id": self.id,
            "name": self.name,
            "description": self.description,
            "version": self.version,
            "created_ms": self.created_ms,
            "updated_ms": self.updated_ms,
            "field": _field_to_json(self.field),
            "field_id": self.field_id,
            "priority": self.priority,
            "scheduled_date": self.scheduled_date,
            "notes": self.notes,
            "operation": {
                "operation_type": self.operation.operation_type,
                "num_drones": self.operation.num_drones,
                "flight_altitude_m": self.operation.flight_altitude_m,
                "planning_mode": self.operation.planning_mode,
                "nominal_speed_ms": self.operation.nominal_speed_ms,
                "overlap_pct": self.operation.overlap_pct,
                "safety_margin_m": self.operation.safety_margin_m,
                "coverage_direction": self.operation.coverage_direction,
                "route_preference": self.operation.route_preference,
            },
            "environment": {
                "temperature_c": self.environment.temperature_c,
                "wind_speed_kmh": self.environment.wind_speed_kmh,
            },
            "fleet": [
                {
                    "drone_id": item.drone_id,
                    "model": item.model,
                    "vendor": item.vendor,
                    "battery_capacity_mah": item.battery_capacity_mah,
                    "liquid_capacity_l": item.liquid_capacity_l,
                    "working_width_m": item.working_width_m,
                }
                for item in self.fleet
            ],
            "products": [
                {
                    "product_id": p.product_id,
                    "name": p.name,
                    "rate_l_per_ha": p.rate_l_per_ha,
                    "tank": p.tank,
                    "concentration_pct": p.concentration_pct,
                    "dilution": p.dilution,
                    "safety_notes": p.safety_notes,
                }
                for p in self.products
            ],
        }

    @classmethod
    def from_json(cls, data: JSONObject) -> "MissionDefinition":
        field_data = _require_object(data.get("field"), "field")
        op_data = _as_object(data.get("operation"))
        env_data = _as_object(data.get("environment"))

        definition = cls(
            name=_require_str(data.get("name"), "name"),
            field=_field_from_json(field_data),
            operation=OperationParams(
                operation_type=_as_str(op_data.get("operation_type"), "spray"),
                num_drones=_as_int(op_data.get("num_drones"), 3),
                flight_altitude_m=_as_opt_float(op_data.get("flight_altitude_m")),
                planning_mode=_as_str(op_data.get("planning_mode"), "automatic"),
                nominal_speed_ms=_as_opt_float(op_data.get("nominal_speed_ms")),
                overlap_pct=_as_opt_float(op_data.get("overlap_pct")),
                safety_margin_m=_as_opt_float(op_data.get("safety_margin_m")),
                coverage_direction=_as_str(
                    op_data.get("coverage_direction"), "auto"
                ),
                route_preference=_as_str(
                    op_data.get("route_preference"), "balanced"
                ),
            ),
            environment=EnvironmentParams(
                temperature_c=_as_float(env_data.get("temperature_c"), 25.0),
                wind_speed_kmh=_as_float(env_data.get("wind_speed_kmh"), 10.0),
            ),
            fleet=[_fleet_item_from_json(i) for i in _as_list(data.get("fleet"))],
            products=[
                _product_from_json(p) for p in _as_list(data.get("products"))
            ],
            description=_as_str(data.get("description"), ""),
            field_id=_as_str(data.get("field_id"), ""),
            priority=_as_str(data.get("priority"), "normal"),
            scheduled_date=_as_str(data.get("scheduled_date"), ""),
            notes=_as_str(data.get("notes"), ""),
        )
        # Preserve identity/versioning when reloading a persisted record.
        if isinstance(data.get("id"), str):
            definition.id = str(data["id"])
        if isinstance(data.get("version"), int):
            definition.version = int(data["version"])
        if isinstance(data.get("created_ms"), int):
            definition.created_ms = int(data["created_ms"])
        if isinstance(data.get("updated_ms"), int):
            definition.updated_ms = int(data["updated_ms"])
        return definition



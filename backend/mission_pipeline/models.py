@dataclass
class MissionPackage:
    """
    The execution-ready artifact produced from a MissionDefinition by the
    Planning Core. Consumed by the Digital Twin; never edited by the UI.

    Fields are plain JSON objects assembled by serializers.build_mission_package
    so this dataclass stays a thin, transport-friendly container.
    """

    definition_id: str
    generated_ms: int
    field_geometry: JSONObject
    routes: list[JSONObject]
    resources: JSONObject
    timeline: JSONObject
    risks: JSONObject
    recommendation: JSONObject
    environment_assessment: JSONObject
    validation: JSONObject
    execution: JSONObject

    def to_json(self) -> JSONObject:
        return {
            "definition_id": self.definition_id,
            "generated_ms": self.generated_ms,
            "field_geometry": self.field_geometry,
            "routes": list(self.routes),
            "resources": self.resources,
            "timeline": self.timeline,
            "risks": self.risks,
            "recommendation": self.recommendation,
            "environment_assessment": self.environment_assessment,
            "validation": self.validation,
            "execution": self.execution,
        }


